package dev.dimension.flare.ui.codegen

internal data class SwiftUIPluginDefinition(
    val moduleName: String,
    val kotlinModuleName: String,
    val primitives: List<PrimitiveDefinition>,
)

/**
 * Generates the language-boundary plumbing which otherwise has to be repeated for every
 * SwiftUI primitive. The native module still owns the actual SwiftUI View implementation.
 */
internal object FlareSwiftUIGenerator {
    fun renderPlugin(plugin: SwiftUIPluginDefinition): String =
        buildString {
            appendLine("// Generated by Flare UI. Do not edit.")
            appendLine("@preconcurrency import ${plugin.kotlinModuleName}")
            appendLine("import Foundation")
            appendLine("import FlareUISwiftUI")
            appendLine()
            appendPlugin(plugin)
            plugin.primitives.forEach { primitive ->
                appendLine()
                appendNode(primitive)
            }
        }

    private fun StringBuilder.appendPlugin(plugin: SwiftUIPluginDefinition) {
        appendLine(
            "public nonisolated final class " +
                "${plugin.moduleName}SwiftUIPlugin: NSObject, FlareSwiftUIPlugin {",
        )
        appendLine("  public override init() {}")
        appendLine()
        appendLine(
            "  public nonisolated func install(" +
                "registrar: FlareSwiftUINodeRegistrar) {",
        )
        plugin.primitives.forEach { primitive ->
            appendLine("    registrar.register(")
            appendLine(
                "      component: ${primitive.apiName}WidgetCompanion.shared.Type,",
            )
            appendLine(
                "      factory: SwiftUI${primitive.apiName}Node.init(tree:)",
            )
            appendLine("    )")
        }
        appendLine("  }")
        appendLine()
        appendLine("  @MainActor")
        appendLine(
            "  public func installViews(" +
                "into registry: FlareSwiftUIRendererRegistry) {",
        )
        plugin.primitives.forEach { primitive ->
            appendLine(
                "    registry.register(" +
                    "SwiftUI${primitive.apiName}Node.self)",
            )
        }
        appendLine("  }")
        appendLine("}")
    }

    private fun StringBuilder.appendNode(primitive: PrimitiveDefinition) {
        appendLine(
            "nonisolated final class SwiftUI${primitive.apiName}Node: " +
                "FlareSwiftUINode, ${primitive.apiName}Widget {",
        )

        primitive.parameters
            .filter { parameter -> parameter.kind == ParameterKind.Slot }
            .forEach { parameter ->
                appendLine("  let ${parameter.name}: FlareSwiftUIChildren")
            }
        primitive.parameters
            .filter { parameter -> parameter.kind == ParameterKind.Property }
            .forEach { parameter ->
                if (parameter.isCallback()) {
                    appendLine(
                        "  private var ${parameter.name}Action: " +
                            "${parameter.swiftType()} = {}",
                    )
                } else {
                    val type = parameter.swiftType()
                    val initializer = parameter.swiftInitialValue()
                    val declaredType =
                        if (initializer == "nil" && !type.endsWith("?")) {
                            "$type!"
                        } else {
                            type
                        }
                    appendLine(
                        "  private(set) var ${parameter.name}: " +
                            "$declaredType = $initializer",
                    )
                }
            }
        if (
            primitive.parameters.any { parameter ->
                parameter.kind != ParameterKind.Modifier
            }
        ) {
            appendLine()
        }

        appendLine("  override init(tree: FlareSwiftUITree) {")
        primitive.parameters
            .filter { parameter -> parameter.kind == ParameterKind.Slot }
            .forEach { parameter ->
                appendLine(
                    "    ${parameter.name} = FlareSwiftUIChildren(tree: tree)",
                )
            }
        appendLine("    super.init(tree: tree)")
        appendLine("  }")

        primitive.parameters
            .filter { parameter -> parameter.kind == ParameterKind.Property }
            .forEach { parameter ->
                appendLine()
                appendSetter(parameter)
                if (parameter.isCallback()) {
                    appendLine()
                    appendLine(
                        "  func perform${parameter.name.toKotlinName()}() {",
                    )
                    appendLine("    ${parameter.name}Action()")
                    appendLine("  }")
                }
            }

        val slots =
            primitive.parameters.filter { parameter ->
                parameter.kind == ParameterKind.Slot
            }
        if (slots.isNotEmpty()) {
            appendLine()
            appendLine("  override func children(slot: FlareSlotId) -> FlareChildren {")
            if (slots.size == 1) {
                val slot = slots.single()
                appendLine("    precondition(")
                appendLine(
                    "      slot == ${primitive.apiName}WidgetCompanion.shared." +
                        slot.name.toKotlinName() + ",",
                )
                appendLine(
                    "      \"${primitive.apiName} does not expose slot '\\(slot)'.\"",
                )
                appendLine("    )")
                appendLine("    return ${slot.name}")
            } else {
                slots.forEach { slot ->
                    appendLine(
                        "    if slot == ${primitive.apiName}WidgetCompanion.shared." +
                            slot.name.toKotlinName() + " {",
                    )
                    appendLine("      return ${slot.name}")
                    appendLine("    }")
                }
                appendLine(
                    "    preconditionFailure(" +
                        "\"${primitive.apiName} does not expose slot '\\(slot)'.\")",
                )
            }
            appendLine("  }")
        }

        val callbacks =
            primitive.parameters.filter { parameter -> parameter.isCallback() }
        if (callbacks.isNotEmpty()) {
            appendLine()
            appendLine("  override func dispose() {")
            callbacks.forEach { callback ->
                appendLine("    ${callback.name}Action = {}")
            }
            appendLine("  }")
        }
        appendLine("}")
    }

    private fun StringBuilder.appendSetter(parameter: PrimitiveParameter) {
        val escaping = if (parameter.isCallback()) "@escaping " else ""
        appendLine(
            "  func set${parameter.name.toKotlinName()}(" +
                "value: $escaping${parameter.swiftType()}) {",
        )
        if (parameter.isCallback()) {
            appendLine("    ${parameter.name}Action = value")
        } else {
            appendLine("    ${parameter.name} = value")
            appendLine("    invalidate()")
        }
        appendLine("  }")
    }

    private fun PrimitiveParameter.isCallback(): Boolean = type == "kotlin.Function0<kotlin.Unit>"

    private fun PrimitiveParameter.swiftType(): String {
        val nullable = type.endsWith("?")
        val nonNullType = type.removeSuffix("?")
        val swiftType =
            when (nonNullType) {
                "kotlin.String" -> "String"
                "kotlin.Boolean" -> "Bool"
                "kotlin.Byte" -> "Int8"
                "kotlin.Short" -> "Int16"
                "kotlin.Int" -> "Int32"
                "kotlin.Long" -> "Int64"
                "kotlin.Float" -> "Float"
                "kotlin.Double" -> "Double"
                "kotlin.Function0<kotlin.Unit>" -> "() -> Void"
                else -> nonNullType.substringAfterLast('.')
            }
        return if (nullable) "$swiftType?" else swiftType
    }

    private fun PrimitiveParameter.swiftInitialValue(): String {
        if (type.endsWith("?")) return "nil"
        return when (type) {
            "kotlin.String" -> "\"\""

            "kotlin.Boolean" -> "false"

            "kotlin.Byte",
            "kotlin.Short",
            "kotlin.Int",
            "kotlin.Long",
            "kotlin.Float",
            "kotlin.Double",
            -> "0"

            else -> "nil"
        }
    }
}
