use std::{collections::BTreeSet, error::Error, fmt::Write, fs, path::PathBuf};

use flare_ffi::{PRESENTER_BINDINGS, PresenterBinding};

const HEADER: &str = "// Generated by cargo xtask bindings; do not edit.\n\n";

fn render(bindings: &[PresenterBinding]) -> Result<(String, String), Box<dyn Error>> {
    let mut types = BTreeSet::new();
    let mut properties = BTreeSet::new();
    for binding in bindings {
        if !types.insert(binding.presenter)
            || !types.insert(binding.subscription)
            || !properties.insert(binding.kotlin_binding)
        {
            return Err(format!("duplicate presenter adapter name: {}", binding.presenter).into());
        }
    }

    let mut kotlin = format!("{HEADER}package dev.dimension.flare.common\n\n");
    for name in types {
        writeln!(kotlin, "import dev.dimension.flare.rust.{name}")?;
    }
    let mut swift = format!("{HEADER}import FlareRust\n");
    for binding in bindings {
        let PresenterBinding {
            presenter,
            subscription,
            kotlin_binding,
        } = binding;
        write!(
            kotlin,
            r#"
internal val {kotlin_binding} =
    RustPresenterBinding(
        key = "rust.{presenter}",
        snapshot = {presenter}::snapshot,
        subscribe = {presenter}::subscribe,
        nextState = {subscription}::nextState,
        stop = {subscription}::stop,
        shutdown = {presenter}::shutdown,
    )
"#
        )?;
        write!(
            swift,
            "\nextension {subscription}: RustStateSubscription {{}}\n\
             extension {presenter}: RustPresenterSource {{}}\n"
        )?;
    }
    Ok((kotlin, swift))
}

fn main() -> Result<(), Box<dyn Error>> {
    let paths: Vec<PathBuf> = std::env::args_os().skip(1).map(PathBuf::from).collect();
    let [kotlin_path, swift_path] = paths.as_slice() else {
        return Err("usage: presenter-bindings <Kotlin output> <Swift output>".into());
    };
    let (kotlin, swift) = render(PRESENTER_BINDINGS)?;
    fs::write(kotlin_path, kotlin)?;
    fs::write(swift_path, swift)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn multiple_presenters_generate_both_adapters_and_collisions_are_rejected() {
        let first = PresenterBinding {
            presenter: "CounterPresenter",
            subscription: "CounterSubscription",
            kotlin_binding: "counterPresenterBinding",
        };
        let mut second = PresenterBinding {
            presenter: "ProfilePresenter",
            subscription: "ProfileSubscription",
            kotlin_binding: "profilePresenterBinding",
        };
        let (kotlin, swift) = render(&[first, second]).unwrap();
        assert!(kotlin.contains("snapshot = CounterPresenter::snapshot"));
        assert!(kotlin.contains("nextState = ProfileSubscription::nextState"));
        assert!(swift.contains("extension CounterPresenter: RustPresenterSource {}"));
        assert!(swift.contains("extension ProfileSubscription: RustStateSubscription {}"));
        second.kotlin_binding = "counterPresenterBinding";
        assert!(render(&[first, second]).is_err());
    }
}
