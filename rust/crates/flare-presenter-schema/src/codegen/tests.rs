use super::*;

#[test]
fn rejects_names_that_collide_after_native_normalization() {
    fn acronym() -> crate::Schema {
        crate::Schema {
            name: "URLPresenter",
            declaration: "",
            dependencies: &[],
            native_types: &["URLPresenter"],
        }
    }
    fn normalized() -> crate::Schema {
        crate::Schema {
            name: "UrlPresenter",
            declaration: "",
            dependencies: &[],
            native_types: &["UrlPresenter"],
        }
    }
    let error = export(&[acronym, normalized], "core", "exporter", &[]).unwrap_err();
    assert!(error.to_string().contains("both export as UrlPresenter"));
}

const CONTRACT: &str = r"
    pub struct ExampleState { pub value: String }
    pub enum ExampleError { Closed, InvalidName { value: String } }
    pub struct ExamplePresenter {
        session: PresenterSession<ExampleState, String, ExampleError>,
    }
    impl ExamplePresenter {
        pub fn new(initial: String) -> (Self, impl Future<Output = ()>) { todo!() }
        pub async fn rename(&self, value: String) -> Result<ExampleState, ExampleError> { todo!() }
    }
";

fn rejected(source: &str, message: &str) {
    let input = syn::parse_file(source).unwrap();
    let error = expand_presenter(&input).unwrap_err();
    assert!(error.to_string().contains(message), "{error}");
}

#[test]
fn rejects_contracts_that_could_diverge_between_core_and_ffi() {
    for (from, to, message) in [
        (
            "pub value: String",
            "#[cfg(feature = \"extra\")] pub value: String",
            "conditional",
        ),
        (
            "pub value: String",
            "value: String",
            "fields must be public",
        ),
        (
            "pub struct ExampleState",
            "pub struct ExampleState<T>",
            "must be concrete",
        ),
        ("Closed,", "RuntimeUnavailable,", "unit Closed"),
        ("Closed,", "Closed, RuntimeUnavailable,", "reserved for FFI"),
    ] {
        rejected(&CONTRACT.replace(from, to), message);
    }
}

#[test]
fn rejects_unsupported_action_signatures_and_generated_method_collisions() {
    for (from, to, message) in [
        ("&self", "&mut self", "require &self"),
        ("pub async fn rename", "pub fn rename", "must be async"),
        ("fn rename", "fn snapshot", "generated by #[presenter]"),
        ("fn rename", "fn rename<T>", "concrete Rust methods"),
        (
            "Result<ExampleState, ExampleError>",
            "Result<ExampleState, OtherError>",
            "presenter error",
        ),
        ("pub fn new", "fn new", "public new"),
    ] {
        rejected(&CONTRACT.replace(from, to), message);
    }
}

#[test]
fn rejects_dtos_whose_export_could_diverge_from_the_core_definition() {
    for (source, message) in [
        ("struct Profile { pub name: String }", "must be public"),
        ("pub struct Profile<T> { pub name: T }", "must be concrete"),
        ("pub struct Profile(String);", "named public fields"),
        (
            "pub struct Profile { name: String }",
            "fields must be public",
        ),
        (
            "pub struct Profile { #[cfg(test)] pub name: String }",
            "conditional",
        ),
        ("#[cfg(test)] pub enum Status { Ready }", "conditional"),
        ("pub enum Status { #[cfg(test)] Ready }", "conditional"),
        (
            "pub enum Status { Ready { #[cfg(test)] name: String } }",
            "conditional",
        ),
        ("pub enum Status { Ready = 1 }", "discriminants"),
        ("pub enum Status<T> { Ready(T) }", "concrete"),
    ] {
        let item = syn::parse_str(source).unwrap();
        let error = dto::expand(&item).unwrap_err();
        assert!(error.to_string().contains(message), "{source}: {error}");
    }
}

#[test]
fn collects_nested_types_and_rejects_unsupported_type_shapes() {
    let mut dependencies = Vec::new();
    let ty = syn::parse_quote!(HashMap<String, Vec<Option<Profile>>>);
    let exported = dto::export_type(&ty, &mut dependencies).unwrap();
    assert_eq!(
        dependencies[0].to_string(),
        quote!(Profile::__schema).to_string()
    );
    let expected: Type = syn::parse_quote!(::std::collections::HashMap<::std::string::String, ::std::vec::Vec<::std::option::Option<Profile>>>);
    assert_eq!(quote!(#exported).to_string(), quote!(#expected).to_string());
    for source in [
        "&Profile",
        "(Profile, String)",
        "Page<Profile>",
        "domain::Profile",
        "Option<Profile, String>",
        "Vec<'static>",
        "usize",
        "<T as Profile>::State",
        "UiState",
        "UiState<Profile, String>",
        "UiState<&Profile>",
        "UiState<()>",
    ] {
        assert!(
            dto::export_type(&syn::parse_str(source).unwrap(), &mut Vec::new()).is_err(),
            "{source}"
        );
    }
}

#[test]
fn specializes_ui_state_at_any_dto_depth() {
    let ty = syn::parse_quote!(Option<UiState<Vec<UiState<Profile>>>>);
    let mut dependencies = Vec::new();
    let exported = dto::export_type(&ty, &mut dependencies).unwrap();
    assert_eq!(
        quote!(#exported).to_string(),
        quote!(::std::option::Option<UiStateOfVecOfUiStateOfProfile>).to_string()
    );
    let schema = &dependencies[0];
    // Dependencies include both specializations and the typed payload/error metadata.
    let schema = schema.to_string();
    assert!(schema.contains("UiStateOfProfile"));
    assert!(schema.contains("Profile :: __schema"));
    assert!(schema.contains("UiError :: __schema"));
}
